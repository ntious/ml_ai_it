"""Serve the built artifact under a GitHub-project-style prefix and test routes.

HEAD requests exercise real HTTP resolution without loading large ZIP payloads.
This is not browser rendering, accessibility, or a production hosting test.
"""
from functools import partial
from html.parser import HTMLParser
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
import shutil
import tempfile
import threading
from urllib.parse import urljoin, urlsplit
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.values = []

    def handle_starttag(self, tag, attrs):
        if tag == "base": return
        for name, value in attrs:
            if name in {"href", "src"}:
                self.values.append(value)


class QuietHandler(SimpleHTTPRequestHandler):
    def log_message(self, format, *args):
        pass


with tempfile.TemporaryDirectory() as temporary:
    # Copies the actual generated bytes; a symlink is unnecessary on Windows.
    shutil.copytree(ROOT / "site", Path(temporary) / "ml_ai_it")
    server = ThreadingHTTPServer(("127.0.0.1", 0), partial(QuietHandler, directory=temporary))
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    base = f"http://127.0.0.1:{server.server_port}/ml_ai_it/"
    routes = {base}
    try:
        for page in (ROOT / "site").rglob("*.html"):
            page_url = urljoin(base, page.relative_to(ROOT / "site").as_posix())
            routes.add(page_url)
            parser = Links()
            parser.feed(page.read_text(encoding="utf-8"))
            for value in parser.values:
                if urlsplit(value).scheme or urlsplit(value).netloc:
                    continue
                target = urljoin(page_url, value).split("#", 1)[0]
                assert target.startswith(base), f"Link escapes project prefix: {value}"
                routes.add(target)
        for route in sorted(routes):
            with urlopen(Request(route, method="HEAD"), timeout=10) as response:
                assert response.status == 200, route
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
print(f"Verified {len(routes)} served HTTP routes under /ml_ai_it/ including downloads. Browser and assistive-technology review remains pending.")
